"""Bakes the companion screen's backdrop into ui_backdrop.c: the same night
sky, hexagon lattice, stars and horizon glow as RemotePilot PSP's XMB
background (art/make_xmb_art.py, with the same seed), without its words, so
the app opens on the picture its icon promised.

    python psp/device/ui/make_backdrop.py

The output (480x272, 8-bit RGB) is committed: the PSP build needs no Python.
"""
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "art"))
import make_xmb_art  # noqa: E402


def main():
    image = make_xmb_art.backdrop(480, 272, 2026).resize((480, 272), Image.LANCZOS).convert("RGB")
    data = image.tobytes()
    lines = ["/* ui_backdrop.c - generated by make_backdrop.py from art/make_xmb_art.py: do not",
             "edit. RemotePilot PSP's XMB backdrop, without its words; ours, drawn from shapes. */",
             '#include "ui.h"', "", "const unsigned char ui_backdrop_rgb[UI_W * UI_H * 3] = {"]
    for k in range(0, len(data), 32):
        lines.append("\t" + ",".join(str(b) for b in data[k:k + 32]) + ",")
    lines += ["};", ""]
    (HERE / "ui_backdrop.c").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote ui_backdrop.c ({len(data)} bytes)")


if __name__ == "__main__":
    main()
