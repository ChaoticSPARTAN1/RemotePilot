"""Bakes the companion screen's fonts into ui_fonts.c: anti-aliased glyphs
(8-bit coverage) for the characters the screens use.

    python psp/device/ui/make_fonts.py

Fonts (fonts/ beside this file, each with its licence):
  Audiowide (SIL Open Font License, OFL.txt): titles;
  DejaVu Sans and Sans Bold (Bitstream Vera licence, public-domain changes,
  LICENSE_DEJAVU): everything else.
The output is committed, so the PSP build needs no Python or Pillow.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
FONTS = HERE / "fonts"
# name, file, pixel size
SETS = (("title", "Audiowide-Regular.ttf", 21), ("big", "DejaVuSans-Bold.ttf", 22),
        ("head", "DejaVuSans-Bold.ttf", 14), ("body", "DejaVuSans.ttf", 12), ("label", "DejaVuSans-Bold.ttf", 10))
CHARS = [chr(c) for c in range(32, 127)] + ["·", "…", "–", "→", "✓", "°", "□", "△", "○", "✕", "↑", "↓"]


def bake(name, file, size):
    font = ImageFont.truetype(str(FONTS / file), size)
    ascent, descent = font.getmetrics()
    glyphs, alpha = [], bytearray()
    for ch in CHARS:
        advance = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        width, height = max(0, x1 - x0), max(0, y1 - y0)
        if width and height:
            image = Image.new("L", (width, height), 0)
            ImageDraw.Draw(image).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            data = image.tobytes()
        else:
            data = b""
        glyphs.append((ord(ch), advance, x0, y0, width, height, len(alpha)))
        alpha += data
    lines = [f"static const struct ui_glyph {name}_glyphs[] = {{"]
    lines += [f"\t{{{cp}, {adv}, {x}, {y}, {w}, {h}, {off}}}," for cp, adv, x, y, w, h, off in glyphs]
    lines += ["};", f"static const unsigned char {name}_alpha[] = {{"]
    for k in range(0, len(alpha), 24):
        lines.append("\t" + ",".join(str(b) for b in alpha[k:k + 24]) + ",")
    lines += ["};", f"const struct ui_font ui_font_{name} = {{{ascent}, {ascent + descent}, {len(glyphs)}, "
              f"{name}_glyphs, {name}_alpha}};", ""]
    return "\n".join(lines), len(alpha)


def main():
    parts = ['/* ui_fonts.c - generated by make_fonts.py: do not edit. Glyphs of Audiowide',
             '(SIL Open Font License, fonts/OFL.txt) and DejaVu Sans (Bitstream Vera licence,',
             'fonts/LICENSE_DEJAVU). */', '#include "ui.h"', '']
    total = 0
    for name, file, size in SETS:
        text, size_bytes = bake(name, file, size)
        parts.append(text)
        total += size_bytes
    (HERE / "ui_fonts.c").write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote ui_fonts.c ({total} glyph bytes)")


if __name__ == "__main__":
    main()
